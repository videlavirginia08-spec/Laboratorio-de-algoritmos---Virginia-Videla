#2. Calcular el sueldo mensual de un operario conociendo la cantidad de horas trabajadas y el valor por hora.

cantidadhoras = int(input ("Escriba la cantidad de horas mensuales que trabaja."))
valorporhora = int(input ("Escriba el monto que cobra por hora."))

sueldo = cantidadhoras*valorporhora
print(f"Su sueldo mensual es de: {sueldo}")